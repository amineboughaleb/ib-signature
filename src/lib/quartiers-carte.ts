/* À cette latitude, un degré de longitude vaut cos(33,6°) degré de latitude. */
const K = Math.cos((33.59 * Math.PI) / 180);
const METRES_PAR_DEGRE = 111320;

function dedans(lat: number, lng: number, p: [number, number][]): boolean {
  let oui = false;
  for (let i = 0, j = p.length - 1; i < p.length; j = i++) {
    const [yi, xi] = p[i];
    const [yj, xj] = p[j];
    if (yi > lat !== yj > lat && lng < ((xj - xi) * (lat - yi)) / (yj - yi) + xi) oui = !oui;
  }
  return oui;
}

/** La distance, en mètres, d'un point au bord le plus proche d'un contour. */
function distanceAuBord(lat: number, lng: number, p: [number, number][]): number {
  let mini = Infinity;
  const px = lng * K;
  for (let i = 0, j = p.length - 1; i < p.length; j = i++) {
    const ax = p[j][1] * K, ay = p[j][0];
    const bx = p[i][1] * K, by = p[i][0];
    const dx = bx - ax, dy = by - ay;
    const l2 = dx * dx + dy * dy;
    const t = l2 ? Math.max(0, Math.min(1, ((px - ax) * dx + (lat - ay) * dy) / l2)) : 0;
    const d = Math.hypot(px - (ax + t * dx), lat - (ay + t * dy));
    if (d < mini) mini = d;
  }
  return mini * METRES_PAR_DEGRE;
}

/**
 * Sur la carte, les quartiers sont séparés par le tracé des boulevards : un
 * logement dont la porte donne sur l'un d'eux tombe entre deux contours. Il
 * est alors rattaché au plus proche, s'il est à moins de cette distance.
 * Au-delà, il est hors de la carte et l'on n'invente rien.
 */
export const TOLERANCE_METRES = 120;

/** La zone de la carte où se trouve un point, ou `null` s'il est en dehors. */
export function zoneDuPoint(lat: unknown, lng: unknown): Zone | null {
  const y = Number(lat);
  const x = Number(lng);
  if (!Number.isFinite(y) || !Number.isFinite(x) || (y === 0 && x === 0)) return null;
  for (const z of ZONES_CASABLANCA) if (dedans(y, x, z.polygone)) return z;
  let meilleure: Zone | null = null;
  let mini = TOLERANCE_METRES;
  for (const z of ZONES_CASABLANCA) {
    const d = distanceAuBord(y, x, z.polygone);
    if (d < mini) {
      mini = d;
      meilleure = z;
    }
  }
  return meilleure;
}
